create table if not exists public.paper_portfolio_snapshots (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  trade_id bigint unique references public.paper_trades(id) on delete cascade,
  observed_at timestamptz not null default now(),
  source text not null check (source in ('trade', 'quote_refresh')),
  cash_cents bigint not null check (cash_cents >= 0),
  holdings_cents bigint,
  total_cents bigint,
  source_date timestamptz,
  status text not null check (status in ('fresh', 'stale')),
  constraint paper_portfolio_snapshot_values check (
    (holdings_cents is null and total_cents is null)
    or (holdings_cents is not null and total_cents = cash_cents + holdings_cents)
  )
);

create index if not exists paper_portfolio_snapshots_user_time_idx
  on public.paper_portfolio_snapshots(user_id, observed_at);

alter table public.paper_portfolio_snapshots enable row level security;
do $$ begin
  create policy "users read their own portfolio snapshots"
    on public.paper_portfolio_snapshots for select to authenticated
    using ((select auth.uid()) = user_id);
exception when duplicate_object then null; end $$;

grant select on public.paper_portfolio_snapshots to authenticated;
grant all on public.paper_portfolio_snapshots to service_role;
grant usage, select on sequence public.paper_portfolio_snapshots_id_seq to service_role;

create or replace function public.get_latest_portfolio_snapshots()
returns table (
  user_id uuid,
  cash_cents bigint,
  holdings_cents bigint,
  total_cents bigint,
  source_date timestamptz,
  status text
)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select distinct on (s.user_id)
    s.user_id, s.cash_cents, s.holdings_cents, s.total_cents, s.source_date, s.status
  from public.paper_portfolio_snapshots s
  order by s.user_id, s.observed_at desc, s.id desc;
$$;
revoke all on function public.get_latest_portfolio_snapshots() from public, anon, authenticated;
grant execute on function public.get_latest_portfolio_snapshots() to service_role;
