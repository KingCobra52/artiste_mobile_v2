create table if not exists public.artists (
  id integer generated by default as identity primary key,
  name text not null,
  spotify_id text,
  genre text,
  image_url text,
  tier text,
  youtube_handle text,
  youtube_channel_id text
);

create table if not exists public.artist_snapshots (
  id integer generated by default as identity primary key,
  artist_id integer references public.artists(id),
  listeners integer,
  playcount integer,
  date date
);

create table if not exists public.youtube_snapshots (
  id integer generated by default as identity primary key,
  artist_id integer references public.artists(id),
  subscribers integer,
  total_views bigint,
  date date not null
);

create table if not exists public.recent_youtube_video_snapshots (
  id integer generated by default as identity primary key,
  artist_id integer references public.artists(id),
  video_id text,
  like_count integer,
  view_count integer,
  date date,
  comment_count integer
);

create table if not exists public.lastfm_track_snapshots (
  id integer generated by default as identity primary key,
  artist_id integer references public.artists(id),
  rank integer,
  track_name text,
  track_key text,
  mbid text,
  listeners integer,
  playcount integer,
  date date,
  constraint lastfm_track_snapshots_uniq unique (artist_id, track_key, date)
);

create table if not exists public.lastfm_track_snapshots_backup_aug_18 (
  id integer,
  artist_id integer,
  rank integer,
  track_name text,
  track_key text,
  mbid text,
  listeners integer,
  playcount integer,
  date date
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text,
  bars numeric default 10000
);

create table if not exists public.holdings (
  id integer generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete cascade,
  artist_id integer references public.artists(id),
  shares integer,
  price_per_share double precision,
  bought_at date
);

create unique index if not exists idx_profiles_username_unique
  on public.profiles(username) where username is not null;
create unique index if not exists idx_artists_youtube_channel_id_unique
  on public.artists(youtube_channel_id) where youtube_channel_id is not null;
create index if not exists idx_artist_snapshots_artist_date
  on public.artist_snapshots(artist_id, date);
create index if not exists idx_youtube_snapshots_artist_date
  on public.youtube_snapshots(artist_id, date);
create unique index if not exists youtube_snapshots_uniq
  on public.youtube_snapshots(artist_id, date);
create index if not exists idx_recent_video_snapshots_artist_date
  on public.recent_youtube_video_snapshots(artist_id, date);
create index if not exists idx_recent_video_snapshots_video_date
  on public.recent_youtube_video_snapshots(video_id, date);
create unique index if not exists recent_youtube_video_snapshots_uniq
  on public.recent_youtube_video_snapshots(artist_id, video_id, date);
create index if not exists idx_lastfm_track_snapshots_artist_date
  on public.lastfm_track_snapshots(artist_id, date);
create index if not exists idx_holdings_user_artist
  on public.holdings(user_id, artist_id);

