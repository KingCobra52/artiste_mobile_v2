create table if not exists public.paper_positions (
  user_id uuid not null references auth.users(id) on delete cascade,
  artist_id integer not null references public.artists(id),
  quantity integer not null check (quantity > 0),
  average_cost_cents bigint not null check (average_cost_cents > 0),
  first_purchased_at timestamptz not null default now(),
  primary key (user_id, artist_id)
);

create table if not exists public.paper_trades (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  artist_id integer not null references public.artists(id),
  side text not null check (side in ('buy', 'sell')),
  quantity integer not null check (quantity > 0),
  execution_price_cents bigint not null check (execution_price_cents > 0),
  total_cents bigint not null check (total_cents > 0),
  request_id uuid not null,
  executed_at timestamptz not null default now(),
  unique (user_id, request_id)
);

create index if not exists paper_trades_user_executed_idx
  on public.paper_trades(user_id, executed_at desc);

