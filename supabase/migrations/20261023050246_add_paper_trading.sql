create or replace function public.get_market_snapshots()
returns table (
  artist_id integer,
  snapshot_date date,
  lastfm_playcount bigint,
  youtube_subscribers bigint
)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  with lastfm as (
    select s.artist_id, s.date as snapshot_date, sum(s.playcount)::bigint as playcount
    from public.lastfm_track_snapshots s
    where s.date is not null and s.playcount is not null and s.playcount >= 0
    group by s.artist_id, s.date
  ), youtube as (
    select s.artist_id, s.date as snapshot_date, max(s.subscribers)::bigint as subscribers
    from public.youtube_snapshots s
    where s.date is not null and s.subscribers is not null and s.subscribers >= 0
    group by s.artist_id, s.date
  )
  select coalesce(l.artist_id, y.artist_id),
         coalesce(l.snapshot_date, y.snapshot_date),
         l.playcount,
         y.subscribers
  from lastfm l
  full outer join youtube y
    on y.artist_id = l.artist_id and y.snapshot_date = l.snapshot_date
  order by 1, 2;
$$;
revoke all on function public.get_market_snapshots() from public, anon, authenticated;
grant execute on function public.get_market_snapshots() to service_role;

create or replace function public.execute_paper_trade(
  p_user_id uuid,
  p_artist_id integer,
  p_side text,
  p_quantity integer,
  p_price_cents bigint,
  p_request_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_cash bigint;
  v_after bigint;
  v_total bigint;
  v_position public.paper_positions%rowtype;
  v_existing public.paper_trades%rowtype;
  v_trade_id bigint;
begin
  if p_user_id is null or p_artist_id is null or p_request_id is null
     or p_side is null or p_quantity is null or p_price_cents is null
     or p_side not in ('buy', 'sell') or p_quantity < 1 or p_quantity > 1000000
     or p_price_cents < 1 or p_price_cents > 1000000000 then
    raise exception 'invalid_trade' using errcode = '22023';
  end if;

  select p.cash_cents into v_cash
  from public.profiles p where p.id = p_user_id for update;
  if not found then
    raise exception 'profile_not_ready' using errcode = 'P0002';
  end if;

  select t.* into v_existing from public.paper_trades t
  where t.user_id = p_user_id and t.request_id = p_request_id;
  if found then
    if v_existing.artist_id <> p_artist_id or v_existing.side <> p_side
       or v_existing.quantity <> p_quantity then
      raise exception 'request_id_conflict' using errcode = '23505';
    end if;
    return jsonb_build_object(
      'ok', true, 'code', 'accepted', 'message', 'Trade was already processed.',
      'trade_id', v_existing.id, 'execution_price_cents', v_existing.execution_price_cents,
      'total_cents', v_existing.total_cents, 'cash_cents', v_cash, 'idempotent', true
    );
  end if;

  if not exists (select 1 from public.artists a where a.id = p_artist_id) then
    raise exception 'artist_not_found' using errcode = 'P0002';
  end if;
  v_total := p_quantity::bigint * p_price_cents;
  if v_total > 9000000000000000 then
    raise exception 'trade_too_large' using errcode = '22003';
  end if;

  select p.* into v_position from public.paper_positions p
  where p.user_id = p_user_id and p.artist_id = p_artist_id for update;

  if p_side = 'buy' then
    if v_cash < v_total then
      raise exception 'insufficient_cash' using errcode = 'P0001';
    end if;
    v_after := v_cash - v_total;
    if found then
      update public.paper_positions
      set quantity = v_position.quantity + p_quantity,
          average_cost_cents = round(
            (v_position.quantity::numeric * v_position.average_cost_cents
             + p_quantity::numeric * p_price_cents)
            / (v_position.quantity + p_quantity)
          )::bigint
      where user_id = p_user_id and artist_id = p_artist_id;
    else
      insert into public.paper_positions
        (user_id, artist_id, quantity, average_cost_cents)
      values (p_user_id, p_artist_id, p_quantity, p_price_cents);
    end if;
  else
    if not found or v_position.quantity < p_quantity then
      raise exception 'insufficient_shares' using errcode = 'P0001';
    end if;
    v_after := v_cash + v_total;
    if v_position.quantity = p_quantity then
      delete from public.paper_positions
      where user_id = p_user_id and artist_id = p_artist_id;
    else
      update public.paper_positions
      set quantity = v_position.quantity - p_quantity
      where user_id = p_user_id and artist_id = p_artist_id;
    end if;
  end if;

  update public.profiles set cash_cents = v_after where id = p_user_id;
  insert into public.paper_trades
    (user_id, artist_id, side, quantity, execution_price_cents, total_cents, request_id)
  values
    (p_user_id, p_artist_id, p_side, p_quantity, p_price_cents, v_total, p_request_id)
  returning id into v_trade_id;

  return jsonb_build_object(
    'ok', true, 'code', 'accepted', 'message', 'Paper trade completed.',
    'trade_id', v_trade_id, 'execution_price_cents', p_price_cents,
    'total_cents', v_total, 'cash_cents', v_after, 'idempotent', false
  );
end;
$$;
revoke all on function public.execute_paper_trade(uuid, integer, text, integer, bigint, uuid)
  from public, anon, authenticated;
grant execute on function public.execute_paper_trade(uuid, integer, text, integer, bigint, uuid)
  to service_role;
